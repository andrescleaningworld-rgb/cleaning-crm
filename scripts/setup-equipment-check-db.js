#!/usr/bin/env node
/**
 * One-time setup script for the Equipment Check tablet app
 * (docs/equipment-check-spec.md) in the Neon Postgres database
 * (DATABASE_URL). Additive only and safe to re-run — every statement is
 * CREATE ... IF NOT EXISTS. Touches no existing table.
 *
 * Usage:
 *   node scripts/setup-equipment-check-db.js
 *
 * Tables:
 * - equipment_check_link: single row (id = 1) holding the secret tablet
 *   link key + a version counter. "New link" in Equipment replaces the key
 *   and bumps the version, which also signs out any open tablet session.
 * - equipment_staff_pins: one row per Staff ID (the Sheets Staff tab stays
 *   the only people list — no names stored here). pin_hash is NULL until
 *   the person creates their PIN during an open setup window
 *   (setup_allowed_until). Lockout columns mirror hub_workers.
 * - equipment_reports: exactly the spec's field list. staff_id /
 *   equipment_id are the Sheets-side ids (plain TEXT, never a foreign key).
 */

/* eslint-disable @typescript-eslint/no-require-imports -- standalone Node/CommonJS
   script run via `node scripts/x.js`, not bundled into the app; matches every
   other scripts/*.js file in this repo. */

const fs = require("fs");
const path = require("path");
const { neon } = require("@neondatabase/serverless");

function loadEnvLocal() {
  const envPath = path.join(__dirname, "..", ".env.local");
  if (!fs.existsSync(envPath)) return;
  for (const line of fs.readFileSync(envPath, "utf8").split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}

async function main() {
  loadEnvLocal();

  if (!process.env.DATABASE_URL) {
    console.error("Missing DATABASE_URL. Set it in .env.local (or the environment) before running this script.");
    process.exit(1);
  }

  const sql = neon(process.env.DATABASE_URL);

  // The key itself is generated by the app on first use (lib/equipmentCheckDb.ts
  // getOrCreateEquipmentCheckLink), never by this script, so it never
  // appears in a terminal or log.
  await sql`
    CREATE TABLE IF NOT EXISTS equipment_check_link (
      id INT PRIMARY KEY CHECK (id = 1),
      link_key TEXT NOT NULL UNIQUE,
      key_version INT NOT NULL DEFAULT 1,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;
  console.log("equipment_check_link ready.");

  await sql`
    CREATE TABLE IF NOT EXISTS equipment_staff_pins (
      staff_id TEXT PRIMARY KEY,
      pin_hash TEXT,
      setup_allowed_until TIMESTAMPTZ,
      failed_attempts INT NOT NULL DEFAULT 0,
      locked_until TIMESTAMPTZ,
      last_sign_in_at TIMESTAMPTZ,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;
  console.log("equipment_staff_pins ready.");

  await sql`
    CREATE TABLE IF NOT EXISTS equipment_reports (
      id SERIAL PRIMARY KEY,
      staff_id TEXT NOT NULL,
      equipment_id TEXT NOT NULL,
      condition TEXT NOT NULL CHECK (condition IN ('good','damaged','lost')),
      notes_original TEXT,
      notes_english TEXT,
      notes_lang TEXT,
      photo_urls TEXT[] NOT NULL DEFAULT '{}',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;
  await sql`CREATE INDEX IF NOT EXISTS idx_equipment_reports_equipment ON equipment_reports(equipment_id, created_at DESC)`;
  await sql`CREATE INDEX IF NOT EXISTS idx_equipment_reports_staff ON equipment_reports(staff_id, created_at DESC)`;
  console.log("equipment_reports ready.");

  console.log("Done.");
}

main().catch((err) => {
  console.error("Setup script failed:", err);
  process.exit(1);
});
