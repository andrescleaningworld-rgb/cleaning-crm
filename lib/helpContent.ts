// The staff Help page (app/help/staff-help.tsx): every "I want to…" task, in
// English and Spanish, same order and same ids in both. Edit the words here;
// the page only shows them.
//
// How to write a section:
//   - title: the task, as staff would say it ("Add a new account").
//   - steps: 3 to 6 short steps. Put a button's exact label in **double
//     stars**: it shows in bold. Keep button labels in English in the Spanish
//     version too (the app's buttons are in English).
//   - tip: one line.
//   - link (optional): a page to open, shown as a green button.
// Sections are grouped like the side menu: Daily, Work, Office, Settings.
// Only describe what the app does today; leave out anything switched off.

export type HelpLanguage = "en" | "es";
export type HelpGroupKey = "daily" | "work" | "office" | "settings";

export type HelpSection = {
  /** Same id in every language. */
  id: string;
  group: HelpGroupKey;
  /** The menu page it happens on, shown small above the title. */
  page: string;
  title: string;
  steps: string[];
  tip: string;
  link?: { href: string; label: string };
};

/** One row of "Who does what". */
export type WhoRow = { step: string; who: string; what: string };

export type StaffHelpContent = {
  title: string;
  subtitle: string;
  /** The company rule, shown big at the top. */
  rule: string;
  quickStartTitle: string;
  quickStart: string[];
  searchLabel: string;
  searchPlaceholder: string;
  noMatch: string;
  groups: Record<HelpGroupKey, string>;
  tipWord: string;
  who: {
    title: string;
    intro: string;
    stepColumn: string;
    whoColumn: string;
    whatColumn: string;
    flow: WhoRow[];
    checklistTitle: string;
    checklistIntro: string;
    checklist: WhoRow[];
    link: { href: string; label: string };
  };
  sections: HelpSection[];
};

